const variableNames = ['--bg', '--bg-2', '--bg-3', '--border', '--text', '--text-2', '--primary', '--primary-hover', '--primary-text', '--primary-hover-text', '--danger', '--danger-hover', '--card-surface', '--depth-shadow', '--surface-highlight'];

// Choose readable button text for both pastel and saturated accents.
function accentText(hex: string): string {
  const channels = hex.slice(1).match(/../g)!.map(value => {
    const channel = parseInt(value, 16) / 255;
    return channel <= 0.04045 ? channel / 12.92 : ((channel + 0.055) / 1.055) ** 2.4;
  });
  const luminance = channels[0] * 0.2126 + channels[1] * 0.7152 + channels[2] * 0.0722;
  return luminance > 0.179 ? '#111111' : '#ffffff';
}

export function applyTyprTheme(id: string): void {
  const root = document.documentElement;
  for (const name of variableNames) root.style.removeProperty(name);
  root.style.removeProperty('color-scheme');
  const theme = TYPR_THEMES.find(theme => theme.id === id);
  if (!theme) return;
  const dark = theme.mode === 'dark';
  const values = [theme.bg, theme.wash, theme.muted, theme.border, theme.text, theme.textMuted,
    theme.accent, theme.accentHover, accentText(theme.accent), accentText(theme.accentHover),
    theme.danger, theme.danger, theme.surface,
    dark ? 'rgba(0, 0, 0, 0.28)' : 'rgba(30, 25, 45, 0.10)',
    dark ? 'rgba(255, 255, 255, 0.05)' : 'rgba(255, 255, 255, 0.55)'];
  variableNames.forEach((name, index) => root.style.setProperty(name, values[index]));
  root.style.colorScheme = theme.mode;
}
